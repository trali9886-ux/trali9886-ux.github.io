const hostname = self.location.hostname;
const LOCAL_DEVELOPMENT = hostname === "localhost" || hostname === "127.0.0.1" || hostname === "[::1]";
const CACHE_PREFIX = "paperplane-offline-";

self.addEventListener("install", event => {
  event.waitUntil((async () => {
    // Local static-server sessions must switch to the network-only path quickly;
    // production builds continue to save the complete offline test library.
    if (LOCAL_DEVELOPMENT) {
      await self.skipWaiting();
      return;
    }
    const cache = await caches.open(CACHE_NAME);
    for (const url of PRECACHE_URLS) {
      const response = await fetch(url, { cache: "reload" });
      if (!response.ok) throw new Error(`Failed to cache ${url}: ${response.status}`);
      await cache.put(url, response);
    }
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", event => {
  const request = event.request;
  const requestUrl = new URL(request.url);
  if (request.method !== "GET" || requestUrl.origin !== self.location.origin) return;
  if (requestUrl.pathname.startsWith("/published-tests/")) return;

  if (LOCAL_DEVELOPMENT) {
    event.respondWith(fetch(request, { cache: "no-store" }));
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request, { ignoreSearch: true, ignoreVary: true });
    try {
      const response = await fetch(request);
      if (response.ok) await cache.put(request, response.clone());
      return response;
    } catch (error) {
      if (cached) return cached;
      throw error;
    }
  })());
});
